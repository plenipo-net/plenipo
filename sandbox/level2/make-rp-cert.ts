/**
 * Creates the X.509 material an agent platform needs for `x509_san_dns` client identifiers: a test CA,
 * a request-object signing certificate whose DNS SAN is the platform's host, and its private key.
 * Optionally writes the walt.id Wallet API 2 `wallet-service.conf` that trusts this CA.
 *
 *   npx tsx level2/make-rp-cert.ts --dns platform.sandbox.plenipo.test --out level2/state --waltid level2/waltid/config
 *
 * Then start the sandbox with PLATFORM_RP_KEY, PLATFORM_RP_CHAIN and WALLET_RP_ANCHORS pointing at the
 * files (printed at the end), so the certificate survives restarts and real wallets can be told to trust it.
 * Test material only: the CA key is thrown away and nothing here is fit for production.
 */
import { createPrivateKey } from 'node:crypto';
import { mkdirSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { createTestCertificateAuthority } from 'plenipo/testing';

function arg(name: string, fallback?: string): string | undefined {
  const i = process.argv.indexOf(`--${name}`);
  return i >= 0 ? process.argv[i + 1] : fallback;
}

const dns = arg('dns', 'platform.sandbox.plenipo.test')!;
const out = resolve(arg('out', 'level2/state')!);
const waltid = arg('waltid');
if (!/^([a-z0-9-]+\.)+[a-z]{2,63}$/.test(dns)) throw new Error(`--dns ${dns} is not a host name`);

const ca = await createTestCertificateAuthority('Plenipo Sandbox Relying Party CA');
// clientAuth EKU, which walt.id checks on x509_san_dns certificates.
const leaf = await ca.issueLeaf(`https://${dns}`, { eku: { usages: ['1.3.6.1.5.5.7.3.2'] } });
const pem = (b64: string) => `-----BEGIN CERTIFICATE-----\n${b64.match(/.{1,64}/g)!.join('\n')}\n-----END CERTIFICATE-----\n`;
const keyPem = createPrivateKey({ key: leaf.privateJwk as never, format: 'jwk' }).export({ type: 'pkcs8', format: 'pem' }) as string;

mkdirSync(out, { recursive: true });
writeFileSync(join(out, 'rp-ca.pem'), ca.anchorPem);
writeFileSync(join(out, 'rp-chain.pem'), leaf.x5c.map(pem).join(''));
writeFileSync(join(out, 'rp-key.pem'), keyPem, { mode: 0o600 });

if (waltid) {
  const dir = resolve(waltid);
  mkdirSync(dir, { recursive: true });
  writeFileSync(
    join(dir, 'wallet-service.conf'),
    `# Generated by level2/make-rp-cert.ts for x509_san_dns:${dns}
publicBaseUrl = "http://localhost:7006"
publicBaseUrl = \${?WALLET2_PUBLIC_BASE_URL}

# The wallet accepts x509_san_dns request objects only from certificates under these anchors.
clientIdTrust {
  x509TrustAnchors = [
    """${ca.anchorPem.trim()}"""
  ]
}
`,
  );
  console.log(`wrote ${join(dir, 'wallet-service.conf')}`);
}

console.log(`
RP certificate for x509_san_dns:${dns} written to ${out}

Start the sandbox with it:

  PLATFORM_RP_KEY=${join(out, 'rp-key.pem')} \\
  PLATFORM_RP_CHAIN=${join(out, 'rp-chain.pem')} \\
  WALLET_RP_ANCHORS=${join(out, 'rp-ca.pem')} \\
  PLENIPO_PLATFORM_ORIGIN=https://${dns} \\
  npm run sandbox
`);
