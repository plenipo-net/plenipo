import { describe, expect, it } from 'vitest';
import { createSign, generateKeyPairSync } from 'node:crypto';
import { compactVerify, exportJWK, importJWK } from 'jose';
import {
  createInvocation,
  createMandate,
  ecdsaDerToJose,
  externalSignerFromDer,
  generateAgentKey,
  InMemoryNonceStore,
  InMemorySpendingLedger,
  signCompactJwt,
  verifyAuthorization,
  type ExternalSigner,
} from '../src/index.js';
import { createTestPidProvider, createTestWallet } from '../src/testing.js';

/** A stand-in for a KMS: holds the private key in a closure and returns DER signatures, as AWS KMS does. */
function fakeKms() {
  const { privateKey, publicKey } = generateKeyPairSync('ec', { namedCurve: 'P-256' });
  const publicJwk = publicKey.export({ format: 'jwk' });
  const signDer = async (input: Uint8Array) => {
    const s = createSign('SHA256');
    s.update(input);
    return new Uint8Array(s.sign(privateKey));
  };
  return { publicJwk, signDer };
}

describe('external signers', () => {
  it('converts DER to JOSE and the result verifies', async () => {
    const kms = fakeKms();
    const signer = externalSignerFromDer({ alg: 'ES256', signDer: kms.signDer, publicJwk: kms.publicJwk as never });
    const jws = await signCompactJwt({ hello: 'world' }, { alg: 'ES256', typ: 'test+jwt' }, signer);
    const { payload } = await compactVerify(jws, await importJWK(kms.publicJwk as never, 'ES256'));
    expect(JSON.parse(new TextDecoder().decode(payload))).toEqual({ hello: 'world' });
  });

  it('refuses a raw DER signature passed as JOSE', async () => {
    const kms = fakeKms();
    const raw: ExternalSigner = { alg: 'ES256', sign: kms.signDer };
    await expect(signCompactJwt({ a: 1 }, { alg: 'ES256' }, raw)).rejects.toThrow(/JOSE r\|\|s, not DER/);
  });

  it('refuses an algorithm mismatch', async () => {
    const kms = fakeKms();
    const signer = externalSignerFromDer({ alg: 'ES384', signDer: kms.signDer });
    await expect(signCompactJwt({ a: 1 }, { alg: 'ES256' }, signer)).rejects.toThrow(/does not match/);
  });

  it('detects a signer whose key is not the declared public key', async () => {
    const kms = fakeKms();
    const other = fakeKms();
    const signer = externalSignerFromDer({ alg: 'ES256', signDer: kms.signDer, publicJwk: other.publicJwk as never });
    await expect(signCompactJwt({ a: 1 }, { alg: 'ES256' }, signer)).rejects.toThrow(/does not verify/);
  });

  it('rejects malformed DER', () => {
    expect(() => ecdsaDerToJose(new Uint8Array([0x30, 0x02, 0x02, 0x00]), 'ES256')).toThrow();
    expect(() => ecdsaDerToJose(new Uint8Array([0x31, 0x00]), 'ES256')).toThrow(/SEQUENCE/);
    const tooBig = new Uint8Array([0x30, 0x46, 0x02, 0x21, 0x01, ...new Array(32).fill(1), 0x02, 0x21, 0x00, 0x80, ...new Array(31).fill(1)]);
    expect(() => ecdsaDerToJose(tooBig, 'ES256')).toThrow(/too large/);
  });

  it('an agent whose key lives in a KMS can be authorised end to end', async () => {
    const provider = await createTestPidProvider();
    const wallet = await createTestWallet();
    wallet.storePid(await provider.issuePid(wallet.holderJwk, { given_name: 'Maria', family_name: 'Rossi' }));
    const kms = fakeKms();
    const agentJwk = { kty: 'EC', crv: 'P-256', x: kms.publicJwk.x, y: kms.publicJwk.y };
    const m = createMandate({ agentJwk, actions: ['payments.transfer'], limits: { currency: 'EUR', per_operation: 5000 } });
    const chain = { root: await wallet.approveMandate(m), delegations: [] };
    const signer = externalSignerFromDer({ alg: 'ES256', signDer: kms.signDer, publicJwk: agentJwk });
    const inv = await createInvocation(signer, { chain,
      mandateId: m.id, action: 'payments.transfer', amount: { value: 4000, currency: 'EUR' }, aud: 'https://bank.example',
    });
    const d = await verifyAuthorization(chain, inv, {
      trustedIssuers: [provider.trusted], audience: 'https://bank.example',
      nonces: new InMemoryNonceStore(), ledger: new InMemorySpendingLedger(),
    });
    expect(d.decision).toBe('ALLOW');
    // A key generated by the library still works unchanged.
    const k = await generateAgentKey();
    expect((await exportJWK(k.privateKey)).d).toBeDefined();
  });
});
